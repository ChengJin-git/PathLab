export type ViewerTextKey = keyof typeof copy;
export function useViewerText() {
  const { i18n } = useTranslation();
  const language = i18n.language.startsWith("zh")
    ? i18n.language.includes("HK")
      ? "zh-HK"
      : "zh-CN"
    : "en-US";
  return {
    language,
    t: (key: ViewerTextKey) =>
      copy[key][language === "zh-CN" ? 1 : language === "zh-HK" ? 2 : 0],
  };
}
