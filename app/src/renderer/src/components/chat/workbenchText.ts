export function useWorkbenchText() {
  const { i18n } = useTranslation();
  const language = i18n?.language || "en-US";
  const index = language.startsWith("zh")
    ? /HK|TW|Hant/i.test(language)
      ? 2
      : 1
    : 0;
  return (key: keyof typeof copy) => copy[key][index];
}
