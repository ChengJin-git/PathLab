export function useCapabilityText() {
  const { i18n } = useTranslation();
  const index = i18n.language.startsWith("zh")
    ? /HK|TW|Hant/i.test(i18n.language)
      ? 2
      : 1
    : 0;
  return (key: keyof typeof copy) => copy[key][index];
}
