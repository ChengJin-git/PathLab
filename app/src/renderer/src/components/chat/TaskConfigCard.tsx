/**
 * Parse [TASK_CONFIG] block from message content
 */
export function parseTaskConfig(content: string): AgentTaskConfig | null {
  const config = parseLastChatBlockJson<AgentTaskConfig>(content, 'TASK_CONFIG', { allowIncompleteLast: true })
  if (!config) return null

  try {
    if (config && (getTaskFamily(config.task_type) === 'segmentation' || Array.isArray(config.seg_loss_names))) {
      const normalizedLossConfig = normalizeSegmentationLossConfig(config.seg_loss_names, config.seg_loss_weights)
      config.seg_loss_names = normalizedLossConfig.lossNames
      config.seg_loss_weights = normalizedLossConfig.lossWeights
    }

    return normalizeAgentTaskConfig(config)
  } catch {
    return null
  }
}

function resolveSegmentationBackbone(config: AgentTaskConfig): string {
  const segBackbone = typeof config.seg_backbone === 'string' ? config.seg_backbone.trim() : ''
  const encoder = typeof config.encoder === 'string' ? config.encoder.trim() : ''
  return segBackbone || encoder || DEFAULT_SEG_BACKBONE
}

function resolveSegmentationArchitecture(config: AgentTaskConfig, backbone?: string): string {
  const resolvedBackbone = backbone || resolveSegmentationBackbone(config)
  if (isSegFmEncoder(resolvedBackbone)) {
    if (config.seg_architecture && (FM_SEGMENTATION_ARCHITECTURES as readonly string[]).includes(config.seg_architecture)) {
      return config.seg_architecture
    }
    return FM_SEGMENTATION_ARCHITECTURE
  }
  const segArchitecture = typeof config.seg_architecture === 'string' ? config.seg_architecture.trim() : ''
  return segArchitecture || DEFAULT_SEG_ARCHITECTURE
}

function normalizeAgentTaskConfig(config: AgentTaskConfig): AgentTaskConfig {
  const canonicalTaskType = toCanonicalTaskType(config.task_type, config.data_type) || 'wsi_classification'
  const taskMetadata = getTaskMetadata(canonicalTaskType)
  const baseConfig: AgentTaskConfig = {
    ...config,
    task_type: canonicalTaskType,
    data_type: taskMetadata.dataType,
  }

  if (!isSegmentationTask(canonicalTaskType) && !Array.isArray(config.seg_loss_names)) {
    return baseConfig
  }

  const normalizedBackbone = resolveSegmentationBackbone(baseConfig)
  return {
    ...baseConfig,
    seg_backbone: normalizedBackbone,
    seg_architecture: resolveSegmentationArchitecture(baseConfig, normalizedBackbone),
    stratified: baseConfig.stratified ?? true,
  }
}

function normalizeSplitStrategy(
  _taskType: AgentTaskConfig['task_type'],
  splitStrategy: AgentTaskConfig['split_strategy'] | undefined,
  hasPreDefinedSplits = false,
): 'random' | 'k_fold' | 'manual' {
  if (splitStrategy === 'manual') {
    return hasPreDefinedSplits ? 'manual' : 'random'
  }

  return splitStrategy ?? 'random'
}

/**
 * Remove [TASK_CONFIG] block from content for display
 */
export function removeTaskConfigBlock(content: string): string {
  return stripChatBlocks(content, 'TASK_CONFIG').trim()
}

export function TaskConfigCard({ config: initialConfig, onSubmitSuccess, onSubmitError, onConfigChange, messageId, onHelpfulnessFeedback, savedHelpfulnessFeedback, submitTrigger }: TaskConfigCardProps) {
  const { t } = useTranslation()
  const navigate = useNavigate()
  const { hasUploadingTasks } = useBackgroundTask()
  const { canUseGpu } = useAuth()
  const [config, setConfig] = useState<AgentTaskConfig>(normalizeAgentTaskConfig(initialConfig))
  const [isSubmitting, setIsSubmitting] = useState(false)
  // Initialize submitStatus based on whether task was already submitted (persisted in config)
  // 'pending' = optimistic update, form disabled with positive visual, background work in progress
  const [submitStatus, setSubmitStatus] = useState<'idle' | 'pending' | 'success' | 'error'>(
    initialConfig.submitted_task_id ? 'success' : 'idle'
  )
  const [errorMessage, setErrorMessage] = useState<string>('')
  const [validationErrors, setValidationErrors] = useState<ValidationError[]>([])
  const [showAdvanced, setShowAdvanced] = useState(false)
  // Helpfulness feedback state - initialize with saved feedback if available
  const [helpfulnessFeedback, setHelpfulnessFeedback] = useState<'helpful' | 'not_helpful' | null>(savedHelpfulnessFeedback || null)
  // Learning rate input string state (to support intermediate input like "0.")
  const [learningRateInput, setLearningRateInput] = useState<string>(
    initialConfig.learning_rate?.toString() || '0.0001'
  )
  // Track the last submitTrigger value to detect changes
  // Initialize with the current submitTrigger value to prevent triggering on first render
  const [lastSubmitTrigger, setLastSubmitTrigger] = useState<number | undefined>(submitTrigger)

  // Sync submitStatus when initialConfig.submitted_task_id changes (e.g., after reload)
  useEffect(() => {
    if (initialConfig.submitted_task_id) {
      setSubmitStatus('success')
      setConfig(normalizeAgentTaskConfig(initialConfig))
    }
  }, [initialConfig.submitted_task_id])

  // Sync helpfulnessFeedback when savedHelpfulnessFeedback changes (e.g., after reload)
  useEffect(() => {
    if (savedHelpfulnessFeedback) {
      setHelpfulnessFeedback(savedHelpfulnessFeedback)
    }
  }, [savedHelpfulnessFeedback])

  // Dataset selection state
  const [selectedDatasetId, setSelectedDatasetId] = useState<string | null>(initialConfig.dataset_id || null)
  const [availableDatasets, setAvailableDatasets] = useState<DatasetSummary[]>([])
  const [isLoadingDatasets, setIsLoadingDatasets] = useState(true)

  // Split strategy state - use agent's recommendation if provided
  const [splitStrategy, setSplitStrategy] = useState<'random' | 'k_fold' | 'manual'>(
    normalizeSplitStrategy(initialConfig.task_type, initialConfig.split_strategy)
  )
  const [kFoldSplits, setKFoldSplits] = useState(initialConfig.k_fold_splits || 5)
  const [randomSeed, setRandomSeed] = useState(initialConfig.seed ?? 42)
  const [stratified, setStratified] = useState(initialConfig.stratified ?? true)
  const [hasPreDefinedSplits, setHasPreDefinedSplits] = useState(false)
  const [predefinedSplitCounts, setPredefinedSplitCounts] = useState<{ train: number, val: number, test: number }>({ train: 0, val: 0, test: 0 })

  const shouldMarkSubmissionAsFailed = (error: unknown): error is Error => {
    if (!(error instanceof Error)) return false
    const lowerMessage = error.message.toLowerCase()
    const isDefinitiveStorageError =
      lowerMessage.includes('external storage not responding') ||
      (lowerMessage.includes('storage') && lowerMessage.includes('timed out')) ||
      (lowerMessage.includes('network storage') && lowerMessage.includes('check')) ||
      (lowerMessage.includes('cannot verify accessibility') && lowerMessage.includes('file'))

    if (isDefinitiveStorageError) return true

    if (error instanceof ApiError) {
      return error.isValidationError() || error.isAuthError() || error.code === 'CONFLICT'
    }
    return false
  }

  // Get the currently selected dataset summary (for file_count when WSI list not loaded)
  const normalizedDataType = useMemo(() => {
    if (isSegmentationTask(config.task_type) || config.task_type === 'patch_detection') return 'patch'
    if (isSurvivalTask(config.task_type)) return 'wsi'
    return config.data_type
  }, [config.task_type, config.data_type])

  const compatibleDatasets = useMemo(() => {
    return availableDatasets.filter(dataset => {
      if (!dataset.task_types.includes(config.task_type)) return false
      if (dataset.data_type !== normalizedDataType) return false
      if (isSegmentationTask(config.task_type) || config.task_type === 'patch_detection') {
        return dataset.aggregation_level === 'file'
      }
      return true
    })
  }, [availableDatasets, config.task_type, normalizedDataType])

  const unavailableDatasetIds = useMemo(() => {
    return new Set(
      compatibleDatasets
        .filter(d => d.availability?.status === 'unavailable')
        .map(d => d.dataset_id)
        .filter(Boolean)
    )
  }, [compatibleDatasets])


  const selectedDataset = useMemo(() => {
    return compatibleDatasets.find(d => d.dataset_id === selectedDatasetId) || null
  }, [compatibleDatasets, selectedDatasetId])

  const resolvedSegBackbone = useMemo(() => resolveSegmentationBackbone(config), [config])
  const isFmSegmentation = useMemo(
    () => isSegmentationTask(config.task_type) && isSegFmEncoder(resolvedSegBackbone),
    [config.task_type, resolvedSegBackbone]
  )
  const resolvedSegArchitecture = useMemo(
    () => resolveSegmentationArchitecture(config, resolvedSegBackbone),
    [config, resolvedSegBackbone]
  )
  const unifiedBackboneOptions = useMemo(
    () => [
      {
        group: t('chatComponents.taskConfig.segFoundationModels'),
        options: ENCODER_OPTIONS.filter(option => isSegFmEncoder(option.value)),
      },
      ...BACKBONE_GROUPS.map(group => ({
        group,
        options: SEGMENTATION_BACKBONES.filter(bb => bb.group === group).map(bb => ({
          value: bb.id,
          label: bb.name,
        })),
      })),
    ],
    [t]
  )

  // Load available datasets on mount
  useEffect(() => {
    loadDatasets()
  }, [])

  useEffect(() => {
    if ((isSegmentationTask(config.task_type) || config.task_type === 'patch_detection') && config.data_type !== 'patch') {
      const nextConfig = { ...config, data_type: 'patch' as const }
      setConfig(nextConfig)
      onConfigChange?.(nextConfig)
    } else if (isSurvivalTask(config.task_type) && config.data_type !== 'wsi') {
      const nextConfig = { ...config, data_type: 'wsi' as const }
      setConfig(nextConfig)
      onConfigChange?.(nextConfig)
    }
  }, [config, onConfigChange])

  useEffect(() => {
    const normalizedStrategy = normalizeSplitStrategy(config.task_type, splitStrategy, hasPreDefinedSplits)
    if (normalizedStrategy !== splitStrategy) {
      setSplitStrategy(normalizedStrategy)
    }
  }, [config.task_type, splitStrategy, hasPreDefinedSplits])

  useEffect(() => {
    if (selectedDatasetId && !compatibleDatasets.some(d => d.dataset_id === selectedDatasetId)) {
      setSelectedDatasetId(null)
      setHasPreDefinedSplits(false)
      setPredefinedSplitCounts({ train: 0, val: 0, test: 0 })
    }
  }, [selectedDatasetId, compatibleDatasets])



  // Check if current split strategy is valid (for disabling submit button)
  // Simplified: only use file_count for rough validation since we submit by dataset_id
  const isSplitValid = useMemo(() => {
    if (splitStrategy === 'manual') {
      // For manual/custom splits, check if predefined splits exist
      return hasPreDefinedSplits
    }

    if (!selectedDataset) {
      return false
    }

    const fileCount = selectedDataset.file_count
    if (splitStrategy === 'random') {
      // Need at least 20 samples for 7:1:2 split (rough estimate)
      return fileCount >= 20
    }
    if (splitStrategy === 'k_fold') {
      // Need at least 2*k samples for k-fold (rough estimate)
      return fileCount >= kFoldSplits * 2
    }
    return true
  }, [splitStrategy, kFoldSplits, selectedDataset, hasPreDefinedSplits])

  // Track if we have a pending voice submit (waiting for data to load)
  const [pendingVoiceSubmit, setPendingVoiceSubmit] = useState(false)

  // Voice command submit trigger: when submitTrigger changes, mark pending submit
  useEffect(() => {
    // Only trigger if:
    // 1. submitTrigger is defined and changed
    // 2. Not already submitted or submitting
    if (
      submitTrigger !== undefined &&
      submitTrigger !== lastSubmitTrigger &&
      submitStatus === 'idle' &&
      !isSubmitting
    ) {
      setLastSubmitTrigger(submitTrigger)
      // Mark as pending - will submit when data is ready
      setPendingVoiceSubmit(true)
    }
  }, [submitTrigger, lastSubmitTrigger, submitStatus, isSubmitting])

  // Execute pending voice submit when data is ready
  // Only need dataset selected - backend resolves WSI IDs from dataset_id
  useEffect(() => {
    if (
      pendingVoiceSubmit &&
      !isLoadingDatasets &&
      selectedDatasetId &&
      submitStatus === 'idle' &&
      !isSubmitting
    ) {
      setPendingVoiceSubmit(false)
      handleSubmit()
    }
  }, [pendingVoiceSubmit, isLoadingDatasets, selectedDatasetId, submitStatus, isSubmitting])

  const loadDatasets = async () => {
    setIsLoadingDatasets(true)
    try {
      const result = initialConfig.dataset_id
        ? { items: [await fetchDatasetSummary(initialConfig.dataset_id)] }
        : await fetchAllDatasets(normalizedDataType, { task_type: config.task_type })
      setAvailableDatasets(result.items)
      // If agent provided a dataset_id, verify it exists and set split info
      if (initialConfig.dataset_id) {
        const found = result.items.find(d => d.dataset_id === initialConfig.dataset_id)
        if (found) {
          if (
            found.data_type &&
            getTaskFamily(initialConfig.task_type) === 'classification' &&
            found.data_type !== initialConfig.data_type
          ) {
            const nextConfig = { ...config, data_type: found.data_type as 'wsi' | 'patch' }
            setConfig(nextConfig)
            onConfigChange?.(nextConfig)
          }
          setSelectedDatasetId(initialConfig.dataset_id)
          // Set split info immediately from dataset summary
          const hasSplits = found.has_predefined_splits ?? false
          const counts = found.predefined_split_counts ?? { train: 0, val: 0, test: 0 }
          setHasPreDefinedSplits(hasSplits)
          setPredefinedSplitCounts(counts)
          setSplitStrategy(
            initialConfig.split_strategy
              ? normalizeSplitStrategy(initialConfig.task_type, initialConfig.split_strategy, hasSplits)
              : (hasSplits ? 'manual' : 'random')
          )
        }
      }
    } catch (error) {
      console.error('Failed to load datasets:', error)
    } finally {
      setIsLoadingDatasets(false)
    }
  }

  const updateConfig = (field: keyof AgentTaskConfig, value: any) => {
    const newConfig = { ...config, [field]: value }
    if (field === 'task_type') {
      const canonicalTaskType = toCanonicalTaskType(value) || 'wsi_classification'
      const metadata = getTaskMetadata(canonicalTaskType)
      newConfig.task_type = canonicalTaskType
      newConfig.data_type = metadata.dataType
      if (isSegmentationTask(canonicalTaskType) && newConfig.stratified == null) newConfig.stratified = true
      if (canonicalTaskType === 'patch_detection') {
        newConfig.detection = newConfig.detection || defaultDetectionOptions
        newConfig.batch_size = 2
        newConfig.optimizer = 'adamw'
        newConfig.learning_rate = 0.0001
        if (newConfig.split_strategy === 'k_fold') newConfig.split_strategy = 'random'
      }
    }
    if (field === 'data_type') {
      if (isSegmentationTask(config.task_type) || config.task_type === 'patch_detection') newConfig.data_type = 'patch'
      if (isSurvivalTask(config.task_type)) newConfig.data_type = 'wsi'
    }
    if (field === 'seg_backbone') {
      if (isSegFmEncoder(value as string)) {
        if (!newConfig.seg_architecture || !(FM_SEGMENTATION_ARCHITECTURES as readonly string[]).includes(newConfig.seg_architecture!)) {
          newConfig.seg_architecture = FM_SEGMENTATION_ARCHITECTURE
        }
      } else if (!newConfig.seg_architecture || (FM_SEGMENTATION_ARCHITECTURES as readonly string[]).includes(newConfig.seg_architecture!)) {
        newConfig.seg_architecture = DEFAULT_SEG_ARCHITECTURE
      }
    }
    setConfig(newConfig)
    onConfigChange?.(newConfig)
    // Clear validation error for this field
    setValidationErrors(prev => prev.filter(e => e.field !== field))
  }

  const updateStratified = (value: boolean) => {
    setStratified(value)
    const nextConfig = { ...config, stratified: value }
    setConfig(nextConfig)
    onConfigChange?.(nextConfig)
  }

  const validate = (): boolean => {
    const errors: ValidationError[] = []
    if (!config.task_name?.trim()) {
      errors.push({ field: 'task_name', message: t('chatComponents.taskConfig.validation.taskNameRequired') })
    }
    if (!selectedDatasetId) {
      errors.push({ field: 'dataset_id', message: t('chatComponents.taskConfig.validation.selectDataset') })
    }
    if (splitStrategy === 'manual' && !hasPreDefinedSplits) {
      errors.push({ field: 'split', message: t('chatComponents.taskConfig.validation.noPreDefinedSplits') })
    }
    if (config.learning_rate && (config.learning_rate <= 0 || config.learning_rate > 1)) {
      errors.push({ field: 'learning_rate', message: t('chatComponents.taskConfig.validation.learningRateRange') })
    }
    if (config.epochs && (config.epochs < 1 || config.epochs > 1000)) {
      errors.push({ field: 'epochs', message: t('chatComponents.taskConfig.validation.epochsRange') })
    }
    if (config.batch_size && (config.batch_size < 1 || config.batch_size > 512)) {
      errors.push({ field: 'batch_size', message: t('chatComponents.taskConfig.validation.batchSizeRange') })
    }
    setValidationErrors(errors)
    return errors.length === 0
  }

  const handleSubmit = async () => {
    if (!validate()) return
    if (!selectedDatasetId) return

    // Check if there are any uploading tasks (upload or batch_import) for the selected dataset
    if (hasUploadingTasks(selectedDatasetId)) {
      setSubmitStatus('error')
      setErrorMessage(t('chatComponents.taskConfig.errors.uploadInProgress'))
      return
    }

    // Optimistic update: immediately show positive "pending" state
    // This disables the form and gives user instant feedback instead of a scary spinner
    setIsSubmitting(true)
    setSubmitStatus('pending')
    setErrorMessage('')

    try {
      // Build split config based on strategy
      // Note: for 'manual' strategy, backend reads splits directly from WSI records in database
      let splitConfig: SplitConfig
      if (splitStrategy === 'manual') {
        splitConfig = { strategy: 'manual', seed: randomSeed }
      } else if (splitStrategy === 'k_fold') {
        splitConfig = {
          strategy: 'k_fold',
          n_splits: kFoldSplits,
          seed: randomSeed,
          ...(isSegmentationTask(config.task_type) ? { stratified } : {}),
        }
      } else {
        splitConfig = {
          strategy: 'random',
          ratios: { train: 0.7, val: 0.1, test: 0.2 },
          seed: randomSeed,
          ...(isSegmentationTask(config.task_type) ? { stratified } : {}),
        }
      }

      // Generate task_id on the client so we can navigate immediately
      // without waiting for backend to finish processing 50k+ WSI records
      const taskId = `train_${crypto.randomUUID().replace(/-/g, '').substring(0, 16)}`
      markTrainingSubmissionPending(taskId, config.task_name)

      // Build full TrainingTaskConfig using constants for defaults
      // Send dataset_id instead of wsi_ids — backend resolves WSI IDs from dataset
      const normalizedSegLossConfig = normalizeSegmentationLossConfig(config.seg_loss_names, config.seg_loss_weights)

      const resolvedEncoder = config.encoder ?? DEFAULT_EXTRACTOR
      const resolvedAggregator = config.aggregator ?? DEFAULT_AGGREGATOR
      const resolvedClassifier = config.classifier ?? DEFAULT_PATCH_CLASSIFIER
      const resolvedFeatureExtractor = isSegmentationTask(config.task_type)
        ? resolvedSegBackbone
        : resolvedEncoder
      const featureBatchSize = await resolveFeatureBatchSizeForSubmissionFromQueue(
        config.feature_batch_size,
        resolvedFeatureExtractor,
      )
      let autoDescription: string
      const taskLabel = t(`training.taskSetup.${config.task_type}`)
      if (isSegmentationTask(config.task_type)) {
        autoDescription = `${taskLabel}: ${resolvedSegArchitecture} + ${resolvedSegBackbone}`
      } else if (normalizedDataType === 'wsi') {
        autoDescription = `${taskLabel}: ${resolvedEncoder} + ${resolvedAggregator}`
      } else {
        autoDescription = `${taskLabel}: ${resolvedEncoder} + ${resolvedClassifier}`
      }

      const fullConfig: TrainingTaskConfig = {
        task_id: taskId,
        task_name: config.task_name,
        task_type: config.task_type as TaskType,
        data_type: normalizedDataType,
        task_description: autoDescription,
        dataset_id: selectedDatasetId,
        preprocessing: {
          // Note: tile_size removed - auto-determined by PrePATH-style tiling
          level: config.pyramid_level ?? DEFAULT_PYRAMID_LEVEL,
          // Feature extraction
          feature_extractor: resolvedFeatureExtractor,
          feature_batch_size: featureBatchSize,
          use_gpu: canUseGpu,
          // Tissue segmentation parameters (WSI only)
          sthresh: config.sthresh ?? SEGMENTATION_DEFAULTS.sthresh,
          mthresh: config.mthresh ?? SEGMENTATION_DEFAULTS.mthresh,
          close: config.close ?? SEGMENTATION_DEFAULTS.close,
          use_otsu: config.use_otsu ?? SEGMENTATION_DEFAULTS.useOtsu,
        },
        model: config.task_type === 'patch_detection' ? {
          ...(config.detection || defaultDetectionOptions),
          learning_rate: config.learning_rate ?? 0.0001,
          epochs: config.epochs ?? 50,
          optimizer: config.optimizer ?? 'adamw',
          batch_size: config.batch_size ?? 2,
          early_stopping_patience: config.early_stopping_patience ?? 15,
        } : isSegmentationTask(config.task_type) ? {
          aggregator: '',  // Not used for segmentation
          architecture: resolvedSegArchitecture,
          backbone: resolvedSegBackbone,
          loss_names: normalizedSegLossConfig.lossNames,
          loss_weights: normalizedSegLossConfig.lossWeights,
          learning_rate: config.learning_rate ?? SEG_TRAINING_DEFAULTS.learningRate,
          epochs: config.epochs ?? SEG_TRAINING_DEFAULTS.epochs,
          optimizer: config.optimizer ?? SEG_TRAINING_DEFAULTS.optimizer,
          batch_size: config.batch_size ?? SEG_TRAINING_DEFAULTS.batchSize,
          auto_balance: config.auto_balance ?? false,
          early_stopping_patience: config.early_stopping_patience ?? SEG_TRAINING_DEFAULTS.earlyStoppingPatience,
        } : {
          aggregator: config.aggregator ?? DEFAULT_AGGREGATOR,
          classifier: config.data_type === 'patch' ? (config.classifier ?? DEFAULT_PATCH_CLASSIFIER) : undefined,
          learning_rate: config.learning_rate ?? TRAINING_DEFAULTS.learningRate,
          epochs: config.epochs ?? TRAINING_DEFAULTS.epochs,
          optimizer: config.optimizer ?? TRAINING_DEFAULTS.optimizer,
          batch_size: config.batch_size ?? (config.data_type === 'wsi' ? 1 : TRAINING_DEFAULTS.batchSize),
          auto_balance: config.auto_balance ?? TRAINING_DEFAULTS.autoBalance,
          early_stopping_patience: config.early_stopping_patience ?? TRAINING_DEFAULTS.earlyStoppingPatience,
        },
        split_config: splitConfig
      }

      // Fire-and-forget: send request to backend without waiting for response
      // Backend will process asynchronously; TaskDetailPage will poll until task appears
      void createTrainingTask(fullConfig).then(() => {
        markTrainingSubmissionCreated(taskId)
      }).catch((error) => {
        const msg = error instanceof Error ? error.message : t('chatComponents.taskConfig.errors.failedToCreate')
        if (shouldMarkSubmissionAsFailed(error)) {
          markTrainingSubmissionFailed(taskId, msg)
        }
        console.error('Background task creation request returned error:', msg)
      })

      // Immediately report success and navigate — don't wait for backend
      setSubmitStatus('success')
      setIsSubmitting(false)
      onSubmitSuccess?.(taskId)
    } catch (error) {
      const msg = error instanceof Error ? error.message : t('chatComponents.taskConfig.errors.failedToCreate')
      setSubmitStatus('error')
      setErrorMessage(msg)
      onSubmitError?.(msg)
      setIsSubmitting(false)
    }
  }

  const getFieldError = (field: string) => validationErrors.find(e => e.field === field)?.message

  // Form is disabled after successful submission or during pending optimistic update
  const isFormDisabled = submitStatus === 'success' || submitStatus === 'pending' || isSubmitting
  const defaultBatchSize = config.task_type === 'patch_detection' ? 2 : isSegmentationTask(config.task_type)
    ? SEG_TRAINING_DEFAULTS.batchSize
    : (config.data_type === 'wsi' ? 1 : TRAINING_DEFAULTS.batchSize)

  // Check if this is an AI-recommended config - core fields should be locked
  const isAgentConfig = isAgentRecommendedConfig(initialConfig)

  // Core fields (task_type, data_type, dataset) are locked when AI recommends them
  const isCoreFieldLocked = isAgentConfig || isFormDisabled

  // Common disabled styles
  const disabledInputClass = isFormDisabled ? 'bg-gray-100 text-gray-500 cursor-not-allowed' : ''
  const disabledSelectClass = isFormDisabled ? 'bg-gray-100 text-gray-500 cursor-not-allowed' : ''
  const lockedSelectClass = isCoreFieldLocked ? 'bg-gray-100 text-gray-600 cursor-not-allowed' : ''

  return (
    <div className="mt-4 bg-white border border-gray-200 rounded-2xl shadow-sm overflow-hidden">
      {/* Header */}
      <div className="px-5 py-4 bg-gradient-to-r from-primary-50 to-blue-50 border-b border-gray-100">
        <h3 className="font-semibold text-gray-900 flex items-center gap-2">
          <Play className="w-4 h-4 text-primary-600" />
          {t('chatComponents.taskConfig.title')}
        </h3>
        <p className="text-sm text-gray-500 mt-1">
          {submitStatus === 'success'
            ? t('chatComponents.taskConfig.subtitleSuccess')
            : submitStatus === 'pending'
              ? t('chatComponents.taskConfig.subtitlePending')
              : t('chatComponents.taskConfig.subtitleDefault')}
        </p>
      </div>

      {/* Form Fields */}
      <div className="p-5 space-y-4">
        {/* Task Name */}
        <div>
          <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.taskName')}</label>
          <input
            type="text"
            value={config.task_name || ''}
            onChange={(e) => updateConfig('task_name', e.target.value)}
            disabled={isFormDisabled}
            className={`w-full px-3 py-2 border rounded-lg text-sm focus:ring-2 focus:ring-primary-100 focus:border-primary-400 ${getFieldError('task_name') ? 'border-red-300 bg-red-50' : 'border-gray-200'
              } ${disabledInputClass}`}
            placeholder={t('chatComponents.taskConfig.taskNamePlaceholder')}
          />
          {getFieldError('task_name') && (
            <p className="text-xs text-red-500 mt-1">{getFieldError('task_name')}</p>
          )}
        </div>

        {/* Task Type & Data Level - Locked when AI recommends */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
           <div>
             <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.taskType')}</label>
             <Select
               value={config.task_type}
               onChange={(v) => updateConfig('task_type', v)}
               options={FIELD_OPTIONS.task_type.map(option => ({ ...option, label: t(`training.taskSetup.${option.value}`) }))}
               disabled={isCoreFieldLocked}
               triggerClassName={lockedSelectClass}
             />
           </div>
           <div>
             <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.dataLevel')}</label>
             <Select
               value={normalizedDataType}
               onChange={(v) => updateConfig('data_type', v)}
               options={FIELD_OPTIONS.data_type.map(option => ({ ...option, label: dataTypeLabel(t, option.value) }))}
                disabled={isCoreFieldLocked || isSegmentationTask(config.task_type) || isSurvivalTask(config.task_type)}
               triggerClassName={lockedSelectClass}
             />
           </div>
        </div>

        {/* Dataset Selection - Locked when AI recommends */}
        <div>
          <label className="block text-sm font-medium text-gray-700 mb-1">
            {t('chatComponents.taskConfig.selectDataset')} {selectedDataset && (
              <span className="text-gray-500 font-normal">
                ({t('chatComponents.taskConfig.filesWillBeUsed', { count: selectedDataset.file_count })})
              </span>
            )}
          </label>
          {isLoadingDatasets ? (
            <div className="flex items-center gap-2 text-sm text-gray-500 py-2">
              <Loader2 className="w-4 h-4 animate-spin" />
              {t('chatComponents.taskConfig.loadingDatasets')}
            </div>
           ) : compatibleDatasets.length === 0 ? (
             <p className="text-sm text-amber-600 py-2">{t('chatComponents.taskConfig.noDatasetsAvailable')}</p>
           ) : (
              <Select
                value={selectedDatasetId || ''}
                onChange={(newVal) => {
                  const newDatasetId = newVal || null
                  setSelectedDatasetId(newDatasetId)
                  setValidationErrors(prev => prev.filter(err => err.field !== 'dataset_id'))

                  // Immediately update split info from dataset summary
                  if (newDatasetId) {
                    const selectedDataset = compatibleDatasets.find(d => d.dataset_id === newDatasetId)
                    if (selectedDataset) {
                      const hasSplits = selectedDataset.has_predefined_splits ?? false
                      const counts = selectedDataset.predefined_split_counts ?? { train: 0, val: 0, test: 0 }
                      setHasPreDefinedSplits(hasSplits)
                      setPredefinedSplitCounts(counts)
                      // Auto-select manual split if CSV splits are available
                      if (hasSplits) {
                        setSplitStrategy('manual')
                      } else if (splitStrategy === 'manual') {
                        // No predefined splits — fall back from manual
                        setSplitStrategy('random')
                      }
                    }
                  } else {
                    setHasPreDefinedSplits(false)
                    setPredefinedSplitCounts({ train: 0, val: 0, test: 0 })
                  }
                }}
                options={compatibleDatasets.map(dataset => ({
                  value: dataset.dataset_id || '',
                  label: `${dataset.dataset_name} (${t('chatComponents.taskConfig.filesCount', { count: dataset.file_count })})`,
                  disabled: unavailableDatasetIds.has(dataset.dataset_id || ''),
                }))}
                placeholder={t('chatComponents.taskConfig.selectDatasetPlaceholder')}
                disabled={isCoreFieldLocked}
                triggerClassName={`${getFieldError('dataset_id') ? 'border-red-300 bg-red-50' : ''} ${lockedSelectClass}`}
              />
            )}
           {getFieldError('dataset_id') && (
             <p className="text-xs text-red-500 mt-1">{getFieldError('dataset_id')}</p>
           )}
         </div>

         {/* Data Split Strategy */}
         {selectedDatasetId && (
           <div>
             <label className="block text-sm font-medium text-gray-700 mb-2 flex items-center gap-1.5">
               <Layers className="w-4 h-4 text-gray-400" />
               {t('training.dataSplit.title')}
             </label>
              <div className="grid gap-2 grid-cols-1 sm:grid-cols-3">
               {/* Random Split */}
               <button
                 type="button"
                 disabled={isFormDisabled}
                 onClick={() => !isFormDisabled && setSplitStrategy('random')}
                 className={`p-2.5 rounded-lg border text-left transition-all ${
                   splitStrategy === 'random'
                     ? 'bg-primary-50 border-primary-400 ring-1 ring-primary-400'
                     : 'bg-white border-gray-200 hover:border-primary-300'
                 } ${isFormDisabled ? 'opacity-60 cursor-not-allowed' : 'cursor-pointer'}`}
               >
                 <div className="flex items-center gap-1.5 mb-1">
                   <div className={`w-3 h-3 shrink-0 rounded-full border flex items-center justify-center ${
                     splitStrategy === 'random' ? 'border-primary-500' : 'border-gray-300'
                   }`}>
                     {splitStrategy === 'random' && <div className="w-1.5 h-1.5 rounded-full bg-primary-500" />}
                   </div>
                   <span className="text-xs font-medium text-gray-800">{t('training.dataSplit.randomSplit')}</span>
                 </div>
                 <p className="text-[10px] text-gray-400 pl-4">70 / 10 / 20</p>
               </button>

                {/* K-Fold */}
                {config.task_type !== 'patch_detection' && <button
                 type="button"
                 disabled={isFormDisabled}
                 onClick={() => !isFormDisabled && setSplitStrategy('k_fold')}
                 className={`p-2.5 rounded-lg border text-left transition-all ${
                   splitStrategy === 'k_fold'
                     ? 'bg-primary-50 border-primary-400 ring-1 ring-primary-400'
                     : 'bg-white border-gray-200 hover:border-primary-300'
                 } ${isFormDisabled ? 'opacity-60 cursor-not-allowed' : 'cursor-pointer'}`}
               >
                 <div className="flex items-center gap-1.5 mb-1">
                   <div className={`w-3 h-3 shrink-0 rounded-full border flex items-center justify-center ${
                     splitStrategy === 'k_fold' ? 'border-primary-500' : 'border-gray-300'
                   }`}>
                     {splitStrategy === 'k_fold' && <div className="w-1.5 h-1.5 rounded-full bg-primary-500" />}
                   </div>
                   <span className="text-xs font-medium text-gray-800">{t('training.dataSplit.kFoldCV')}</span>
                 </div>
                 {splitStrategy === 'k_fold' ? (
                   <div className="pl-4 flex items-center gap-1.5">
                     <input
                        type="number"
                        min={2}
                        max={KFOLD_MAX_SPLITS}
                        value={kFoldSplits}
                        onClick={(e) => e.stopPropagation()}
                        onChange={(e) => setKFoldSplits(Math.max(2, Math.min(KFOLD_MAX_SPLITS, parseInt(e.target.value) || 5)))}
                       disabled={isFormDisabled}
                       className="w-11 px-1 py-0.5 border border-gray-300 rounded text-xs"
                     />
                     <span className="text-[10px] text-gray-500">folds</span>
                   </div>
                 ) : (
                   <p className="text-[10px] text-gray-400 pl-4">{t('training.dataSplit.kFoldCVDesc')}</p>
                 )}
                </button>}

                {/* Predefined Split or Upload Prompt */}
               {hasPreDefinedSplits ? (
                 <button
                   type="button"
                   disabled={isFormDisabled}
                   onClick={() => !isFormDisabled && setSplitStrategy('manual')}
                   className={`p-2.5 rounded-lg border text-left transition-all ${
                     splitStrategy === 'manual'
                       ? 'bg-primary-50 border-primary-400 ring-1 ring-primary-400'
                       : 'bg-white border-gray-200 hover:border-primary-300'
                   } ${isFormDisabled ? 'opacity-60 cursor-not-allowed' : 'cursor-pointer'}`}
                 >
                   <div className="flex items-center gap-1.5 mb-1">
                     <div className={`w-3 h-3 shrink-0 rounded-full border flex items-center justify-center ${
                       splitStrategy === 'manual' ? 'border-primary-500' : 'border-gray-300'
                     }`}>
                       {splitStrategy === 'manual' && <div className="w-1.5 h-1.5 rounded-full bg-primary-500" />}
                     </div>
                     <span className="text-xs font-medium text-gray-800">{t('training.dataSplit.customSplit')}</span>
                   </div>
                   <div className="pl-4 flex gap-2 text-[10px] font-medium">
                     <span className="text-green-700">{t('training.dataSplit.train')}:{predefinedSplitCounts.train}</span>
                     <span className="text-blue-600">{t('training.dataSplit.val')}:{predefinedSplitCounts.val}</span>
                     <span className="text-amber-600">{t('training.dataSplit.test')}:{predefinedSplitCounts.test}</span>
                   </div>
                 </button>
                ) : (
                  <button
                    type="button"
                    disabled={isFormDisabled}
                    onClick={() => {
                      if (!isFormDisabled && selectedDataset) {
                        navigate('/upload', {
                          state: { datasetId: selectedDataset.dataset_id, datasetName: selectedDataset.dataset_name },
                        })
                      }
                    }}
                    className={`p-2.5 rounded-lg border border-dashed border-gray-200 bg-gray-50/80 text-left transition-all ${
                      isFormDisabled ? 'opacity-60 cursor-not-allowed' : 'cursor-pointer hover:bg-gray-100 hover:border-gray-300'
                    }`}
                  >
                    <div className="flex items-center gap-1.5 mb-0.5">
                      <UploadCloud className="w-3 h-3 text-gray-400" />
                      <span className="text-xs font-medium text-gray-500">{t('training.dataSplit.uploadSplits')}</span>
                    </div>
                    <p className="text-[10px] text-blue-500 pl-4">{t('training.dataSplit.noSplitsFound')}</p>
                  </button>
                )}
             </div>

            {isSegmentationTask(config.task_type) && splitStrategy !== 'manual' && (
              <label className="mt-3 flex items-start gap-2.5 rounded-lg border border-gray-200 bg-gray-50 px-3 py-2.5 cursor-pointer">
                <Checkbox
                  checked={stratified}
                  onChange={(e) => updateStratified(e.target.checked)}
                  disabled={isFormDisabled}
                  className="mt-0.5"
                />
                <div>
                  <div className="text-xs font-medium text-gray-800">{t('training.dataSplit.stratifiedSplit')}</div>
                  <p className="text-[10px] text-gray-500 mt-0.5">{t('training.dataSplit.stratifiedSplitDesc')}</p>
                </div>
              </label>
            )}
           </div>
         )}

         {/* Segmentation: Architecture & Backbone | Others: Encoder & Model */}
          {config.task_type === 'patch_detection' ? (
            <fieldset disabled={isFormDisabled}>
              <DetectionModelConfig value={config.detection || defaultDetectionOptions} onChange={value => updateConfig('detection', value)} />
            </fieldset>
          ) : isSegmentationTask(config.task_type) ? (
           <>
             <div className="grid grid-cols-2 gap-4">
               <div>
                 <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.segArchitecture')}</label>
                {isFmSegmentation ? (
                    <Select
                      value={resolvedSegArchitecture}
                      onChange={(v) => updateConfig('seg_architecture', v)}
                       options={FM_SEGMENTATION_ARCHITECTURES.map((arch) => ({
                         value: arch,
                         label: `${t(`training.modelConfig.decoder.${arch.replace('_decoder', '')}`, arch.split('_')[0].toUpperCase())} (FM)`
                       }))}
                      disabled={isFormDisabled}
                      triggerClassName={disabledSelectClass}
                    />
                  ) : (
                    <Select
                      value={resolvedSegArchitecture}
                      onChange={(v) => updateConfig('seg_architecture', v)}
                      options={SEGMENTATION_ARCHITECTURES.map(arch => ({ value: arch.id, label: arch.name }))}
                      disabled={isFormDisabled}
                      triggerClassName={disabledSelectClass}
                    />
                  )}
                </div>
                <div>
                  <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.segBackbone')}</label>
                  <Select
                    value={resolvedSegBackbone}
                    onChange={(v) => updateConfig('seg_backbone', v)}
                    options={unifiedBackboneOptions}
                    disabled={isFormDisabled}
                    triggerClassName={disabledSelectClass}
                  />
               </div>
             </div>
             <div>
               <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.segLoss')}</label>
               <div className="flex flex-wrap gap-2">
                 {SEGMENTATION_LOSSES.map(loss => {
                   const selected = (config.seg_loss_names ?? DEFAULT_SEG_LOSS_NAMES).includes(loss.id)
                   return (
                     <button
                       key={loss.id}
                       type="button"
                       disabled={isFormDisabled}
                        onClick={() => {
                          const current = config.seg_loss_names ?? [...DEFAULT_SEG_LOSS_NAMES]
                          let newNames: string[]
                          if (selected) {
                            if (current.length <= 1) return
                            newNames = current.filter(n => n !== loss.id)
                          } else {
                            newNames = [...current, loss.id]
                          }
                          const w = 1 / newNames.length
                          const newWeights = newNames.map(() => Math.round(w * 100) / 100)
                          const newConfig = { ...config, seg_loss_names: newNames, seg_loss_weights: newWeights }
                          setConfig(newConfig)
                          onConfigChange?.(newConfig)
                        }}
                       className={`px-2.5 py-1 text-xs rounded-full border transition-colors ${
                         selected
                           ? 'bg-violet-100 border-violet-300 text-violet-700'
                           : 'bg-gray-50 border-gray-200 text-gray-500 hover:border-gray-300'
                       } ${isFormDisabled ? 'opacity-50 cursor-not-allowed' : ''}`}
                       title={loss.description}
                     >
                       {loss.name}
                     </button>
                   )
                 })}
               </div>
             </div>
           </>
         ) : (
           <div className="grid grid-cols-2 gap-4">
             <div>
               <label className="block text-sm font-medium text-gray-700 mb-1">
                 {config.data_type === 'patch' ? t('chatComponents.taskConfig.featureExtractor') : t('chatComponents.taskConfig.encoder')}
               </label>
               <Select
                 value={config.encoder || 'resnet50'}
                 onChange={(v) => updateConfig('encoder', v)}
                 options={FIELD_OPTIONS.encoder}
                 disabled={isFormDisabled}
                 triggerClassName={disabledSelectClass}
               />
             </div>
             {config.data_type === 'wsi' ? (
               <div>
                 <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.aggregator')}</label>
                 <Select
                   value={config.aggregator || 'abmil'}
                   onChange={(v) => updateConfig('aggregator', v)}
                   options={FIELD_OPTIONS.aggregator}
                   disabled={isFormDisabled}
                   triggerClassName={disabledSelectClass}
                 />
               </div>
             ) : (
               <div>
                 <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.classifierHead', 'Classifier Head')}</label>
                 <Select
                   value={config.classifier || DEFAULT_PATCH_CLASSIFIER}
                   onChange={(v) => updateConfig('classifier', v)}
                   options={FIELD_OPTIONS.classifier}
                   disabled={isFormDisabled}
                   triggerClassName={disabledSelectClass}
                 />
               </div>
             )}
           </div>

        )}

        {/* Advanced Settings Toggle */}
        <button
          type="button"
          onClick={() => setShowAdvanced(!showAdvanced)}
          className={`flex items-center gap-1 text-sm ${isFormDisabled ? 'text-gray-400' : 'text-gray-500 hover:text-gray-700'}`}
        >
          {showAdvanced ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
          {t('chatComponents.taskConfig.advancedSettings')}
        </button>

        {/* Advanced Settings */}
        {showAdvanced && (
          <div className="grid grid-cols-2 gap-4 pt-2 border-t border-gray-100">
            <div>
              <label className="block text-xs font-medium text-gray-600 mb-1">{t('chatComponents.taskConfig.learningRate')}</label>
              <input
                type="text"
                inputMode="decimal"
                value={learningRateInput}
                onChange={(e) => {
                  const val = e.target.value
                  // Allow any valid decimal input pattern (including intermediate states like "0." or ".")
                  if (val === '' || /^[0-9]*\.?[0-9]*$/.test(val)) {
                    setLearningRateInput(val)
                    // Only update config when we have a valid number
                    const num = parseFloat(val)
                    if (!isNaN(num) && num > 0) {
                      updateConfig('learning_rate', num)
                    }
                  }
                }}
                onBlur={() => {
                  // On blur, ensure a valid value (default to 0.0001 if empty/invalid)
                  const num = parseFloat(learningRateInput)
                  if (isNaN(num) || num <= 0) {
                    setLearningRateInput('0.0001')
                    updateConfig('learning_rate', 0.0001)
                  } else {
                    // Normalize the display (remove trailing dots, etc.)
                    setLearningRateInput(num.toString())
                  }
                }}
                disabled={isFormDisabled}
                className={`w-full px-2 py-1.5 border rounded text-sm ${getFieldError('learning_rate') ? 'border-red-300' : 'border-gray-200'
                  } ${disabledInputClass}`}
              />
            </div>
            <div>
              <label className="block text-xs font-medium text-gray-600 mb-1">{t('chatComponents.taskConfig.epochs')}</label>
              <input
                type="number"
                value={config.epochs || 50}
                onChange={(e) => updateConfig('epochs', parseInt(e.target.value))}
                disabled={isFormDisabled}
                className={`w-full px-2 py-1.5 border rounded text-sm ${getFieldError('epochs') ? 'border-red-300' : 'border-gray-200'
                  } ${disabledInputClass}`}
              />
            </div>
            <div>
              <label className="block text-xs font-medium text-gray-600 mb-1">{t('chatComponents.taskConfig.batchSize')}</label>
              <input
                type="number"
                value={config.batch_size ?? defaultBatchSize}
                onChange={(e) => updateConfig('batch_size', parseInt(e.target.value))}
                disabled={isFormDisabled}
                className={`w-full px-2 py-1.5 border rounded text-sm ${getFieldError('batch_size') ? 'border-red-300' : 'border-gray-200'
                  } ${disabledInputClass}`}
              />
            </div>
            <div>
              <label className="block text-xs font-medium text-gray-600 mb-1">{t('chatComponents.taskConfig.randomSeed')}</label>
              <input
                type="number"
                value={randomSeed}
                onChange={(e) => setRandomSeed(parseInt(e.target.value) || 42)}
                disabled={isFormDisabled}
                className={`w-full px-2 py-1.5 border border-gray-200 rounded text-sm ${disabledInputClass}`}
              />
            </div>
          </div>
        )}
      </div>

      {/* Error Message */}
      {submitStatus === 'error' && errorMessage && (
        <div className="mx-5 mb-4 p-3 bg-red-50 border border-red-200 rounded-lg flex items-start gap-2">
          <AlertCircle className="w-4 h-4 text-red-500 mt-0.5 flex-shrink-0" />
          <div>
            <p className="text-sm font-medium text-red-700">{t('chatComponents.taskConfig.errors.failedToCreateTitle')}</p>
            <p className="text-xs text-red-600 mt-0.5">{errorMessage}</p>
            {(() => {
              const lower = errorMessage.toLowerCase()
              if (lower.includes('external storage not responding') ||
                  (lower.includes('storage') && lower.includes('timed out')) ||
                  (lower.includes('not accessible') && lower.includes('file'))) {
                return (
                  <p className="text-xs text-red-500 mt-1.5 flex items-start gap-1">
                    <span>{t('chatComponents.taskConfig.errors.storageUnreachable')}</span>
                  </p>
                )
              }
              return null
            })()}
          </div>
        </div>
      )}

      {/* Success Message */}
      {submitStatus === 'success' && (
        <div className="mx-5 mb-4 p-3 bg-green-50 border border-green-200 rounded-lg flex items-center gap-2">
          <CheckCircle className="w-4 h-4 text-green-500" />
          <p className="text-sm font-medium text-green-700">{t('chatComponents.taskConfig.taskCreatedSuccess')}</p>
        </div>
      )}

      {/* Helpfulness Feedback */}
      {submitStatus === 'success' && !helpfulnessFeedback && (
        <div className="mx-5 mb-4 p-4 bg-blue-50 border border-blue-200 rounded-lg">
          <p className="text-sm font-medium text-blue-800 mb-3">{t('chatComponents.taskConfig.helpfulnessQuestion')}</p>
          <div className="flex gap-2">
            <button
              onClick={() => {
                setHelpfulnessFeedback('helpful')
                const taskId = config.submitted_task_id || ''
                if (messageId && onHelpfulnessFeedback) {
                  onHelpfulnessFeedback(messageId, 'helpful', taskId, 'training', config.task_name || undefined)
                }
              }}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-white border border-blue-200 hover:bg-green-50 hover:border-green-300 hover:text-green-700 text-blue-700 rounded-md text-sm font-medium transition-all shadow-sm"
            >
              <ThumbsUp className="w-3.5 h-3.5" />
              {t('chatComponents.taskConfig.yes')}
            </button>
            <button
              onClick={() => {
                setHelpfulnessFeedback('not_helpful')
                const taskId = config.submitted_task_id || ''
                if (messageId && onHelpfulnessFeedback) {
                  onHelpfulnessFeedback(messageId, 'not_helpful', taskId, 'training', config.task_name || undefined)
                }
              }}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-white border border-blue-200 hover:bg-red-50 hover:border-red-300 hover:text-red-700 text-blue-700 rounded-md text-sm font-medium transition-all shadow-sm"
            >
              <ThumbsDown className="w-3.5 h-3.5" />
              {t('chatComponents.taskConfig.no')}
            </button>
          </div>
        </div>
      )}

      {/* Helpfulness Feedback Submitted */}
      {submitStatus === 'success' && helpfulnessFeedback && (
        <div className="mx-5 mb-4 p-3 bg-gray-50 border border-gray-200 rounded-lg flex items-center gap-2">
          {helpfulnessFeedback === 'helpful' ? (
            <ThumbsUp className="w-4 h-4 text-green-500" />
          ) : (
            <ThumbsDown className="w-4 h-4 text-red-500" />
          )}
          <p className="text-sm text-gray-600">
            {t('chatComponents.taskConfig.feedbackThanks')}
          </p>
        </div>
      )}

      {/* Submit Button */}
      <div className="px-5 py-4 bg-gray-50 border-t border-gray-100">
        <button
          onClick={handleSubmit}
          disabled={isSubmitting || submitStatus === 'success' || submitStatus === 'pending' || !isSplitValid}
          className={`w-full py-2.5 rounded-lg font-medium text-sm
                     flex items-center justify-center gap-2 transition-colors
                     ${submitStatus === 'pending'
                       ? 'bg-green-500 text-white cursor-not-allowed'
                       : submitStatus === 'success'
                         ? 'bg-green-500 text-white cursor-not-allowed'
                         : 'bg-primary-600 text-white hover:bg-primary-700 active:bg-primary-800 disabled:bg-gray-300 disabled:cursor-not-allowed'
                     }`}
        >
          {submitStatus === 'pending' ? (
            <>
              <CheckCircle className="w-4 h-4" />
              {t('chatComponents.taskConfig.creatingTask')}
            </>
          ) : submitStatus === 'success' ? (
            <>
              <CheckCircle className="w-4 h-4" />
              {t('chatComponents.taskConfig.taskCreated')}
            </>
          ) : (
            <>
              <Play className="w-4 h-4" />
              {t('chatComponents.taskConfig.startTraining')}
            </>
          )}
        </button>
      </div>
    </div>
  )
}
