import { useState, useEffect, useMemo } from 'react'
import { useTranslation } from 'react-i18next'
import { Play, AlertCircle, CheckCircle, Loader2, ChevronDown, ChevronUp, Layers, ThumbsUp, ThumbsDown } from 'lucide-react'
import { createTrainingTask, fetchWSIList, fetchDatasets, type TrainingTaskConfig, type DatasetSummary, type SplitConfig } from '../../api'
import { useBackgroundTask } from '../../contexts/BackgroundTaskContext'
import {
  TASK_TYPES,
  DATA_LEVELS,
  ENCODER_OPTIONS,
  AGGREGATOR_OPTIONS,
  OPTIMIZERS,
  DEFAULT_PYRAMID_LEVEL,
  DEFAULT_FEATURE_BATCH_SIZE,
  DEFAULT_EXTRACTOR,
  DEFAULT_AGGREGATOR,
  SEGMENTATION_DEFAULTS,
  TRAINING_DEFAULTS,
} from '../../constants/training'

// Simplified config from Agent (doesn't include wsi_ids, etc.)
// Note: tile_size removed - PrePATH-style tiling auto-determines patch_size based on WSI magnification
export interface AgentTaskConfig {
  task_name: string
  task_description?: string  // Brief description generated by agent
  task_type: 'classification' | 'survival'
  data_type: 'wsi' | 'patch'
  dataset_id?: string  // Dataset UUID from agent

  // Preprocessing parameters (tile_size removed - auto-determined by PrePATH-style)
  pyramid_level?: number       // Pyramid level (0 = highest resolution)
  encoder?: string             // Feature extractor name
  feature_batch_size?: number  // Batch size for feature extraction

  // Tissue segmentation parameters (WSI only)
  sthresh?: number             // Saturation threshold for tissue detection
  mthresh?: number             // Median filter threshold
  close?: number               // Morphological closing kernel size
  use_otsu?: boolean           // Use Otsu's method for thresholding

  // Model parameters
  aggregator?: string          // MIL aggregator (for WSI: abmil, meanmil, etc.)
  learning_rate?: number
  epochs?: number
  batch_size?: number          // Training batch size
  optimizer?: string
  auto_balance?: boolean       // Auto-balance class weights for imbalanced datasets
  early_stopping_patience?: number  // Early stopping patience (default: 10)

  // Split configuration
  split_strategy?: 'random' | 'k_fold' | 'manual'  // Data split strategy recommended by agent (manual = use predefined splits from CSV)
  k_fold_splits?: number       // Number of folds for k-fold CV (default: 5)
  seed?: number                // Random seed for reproducibility (default: 42)

  // Internal state
  submitted_task_id?: string   // Set after successful submission for persistence
}

// Check if config is AI-recommended (has dataset_id set by agent)
// When AI recommends a config, task_type, data_type, and dataset_id should be locked
const isAgentRecommendedConfig = (config: AgentTaskConfig): boolean => {
  // If agent has explicitly set dataset_id, these core fields should be locked
  return !!config.dataset_id
}

interface TaskConfigCardProps {
  config: AgentTaskConfig
  onSubmitSuccess?: (taskId: string) => void
  onSubmitError?: (error: string) => void
  onConfigChange?: (config: AgentTaskConfig) => void
  messageId?: string  // Message ID for helpfulness feedback
  onHelpfulnessFeedback?: (
    messageId: string,
    helpfulness: 'helpful' | 'not_helpful',
    relatedTaskId: string,
    taskType?: 'training' | 'inference' | 'analysis',
    taskTitle?: string
  ) => void
  savedHelpfulnessFeedback?: 'helpful' | 'not_helpful' | null  // Previously saved feedback to restore UI state
  submitTrigger?: number  // When this changes, trigger submit (for voice command)
}

interface ValidationError {
  field: string
  message: string
}

// Field definitions for rendering - using centralized constants
// Note: tile_size removed - now auto-determined by PrePATH-style tiling
const FIELD_OPTIONS = {
  task_type: TASK_TYPES,
  data_type: DATA_LEVELS,
  encoder: ENCODER_OPTIONS,
  aggregator: AGGREGATOR_OPTIONS,
  optimizer: OPTIMIZERS
}

/**
 * Parse [TASK_CONFIG] block from message content
 */
export function parseTaskConfig(content: string): AgentTaskConfig | null {
  const match = content.match(/\[TASK_CONFIG\]([\s\S]*?)\[\/TASK_CONFIG\]/)
  if (!match) return null

  try {
    const jsonStr = match[1].trim()
    return JSON.parse(jsonStr)
  } catch {
    return null
  }
}

/**
 * Remove [TASK_CONFIG] block from content for display
 */
export function removeTaskConfigBlock(content: string): string {
  return content.replace(/\[TASK_CONFIG\][\s\S]*?\[\/TASK_CONFIG\]/g, '').trim()
}

export function TaskConfigCard({ config: initialConfig, onSubmitSuccess, onSubmitError, onConfigChange, messageId, onHelpfulnessFeedback, savedHelpfulnessFeedback, submitTrigger }: TaskConfigCardProps) {
  const { t } = useTranslation()
  const { hasUploadingTasks } = useBackgroundTask()
  const [config, setConfig] = useState<AgentTaskConfig>(initialConfig)
  const [isSubmitting, setIsSubmitting] = useState(false)
  // Initialize submitStatus based on whether task was already submitted (persisted in config)
  // 'pending' = optimistic update, form disabled with positive visual, background work in progress
  const [submitStatus, setSubmitStatus] = useState<'idle' | 'pending' | 'success' | 'error'>(
    initialConfig.submitted_task_id ? 'success' : 'idle'
  )
  const [errorMessage, setErrorMessage] = useState<string>('')
  const [validationErrors, setValidationErrors] = useState<ValidationError[]>([])
  const [showAdvanced, setShowAdvanced] = useState(false)
  // Helpfulness feedback state - initialize with saved feedback if available
  const [helpfulnessFeedback, setHelpfulnessFeedback] = useState<'helpful' | 'not_helpful' | null>(savedHelpfulnessFeedback || null)
  // Learning rate input string state (to support intermediate input like "0.")
  const [learningRateInput, setLearningRateInput] = useState<string>(
    initialConfig.learning_rate?.toString() || '0.0001'
  )
  // Track the last submitTrigger value to detect changes
  // Initialize with the current submitTrigger value to prevent triggering on first render
  const [lastSubmitTrigger, setLastSubmitTrigger] = useState<number | undefined>(submitTrigger)

  // Sync submitStatus when initialConfig.submitted_task_id changes (e.g., after reload)
  useEffect(() => {
    if (initialConfig.submitted_task_id) {
      setSubmitStatus('success')
      setConfig(initialConfig)
    }
  }, [initialConfig.submitted_task_id])

  // Sync helpfulnessFeedback when savedHelpfulnessFeedback changes (e.g., after reload)
  useEffect(() => {
    if (savedHelpfulnessFeedback) {
      setHelpfulnessFeedback(savedHelpfulnessFeedback)
    }
  }, [savedHelpfulnessFeedback])

  // Dataset selection state
  const [selectedDatasetId, setSelectedDatasetId] = useState<string | null>(initialConfig.dataset_id || null)
  const [availableDatasets, setAvailableDatasets] = useState<DatasetSummary[]>([])
  const [isLoadingDatasets, setIsLoadingDatasets] = useState(false)

  // Split strategy state - use agent's recommendation if provided
  const [splitStrategy, setSplitStrategy] = useState<'random' | 'k_fold' | 'manual'>(
    initialConfig.split_strategy || 'random'
  )
  const [kFoldSplits, setKFoldSplits] = useState(initialConfig.k_fold_splits || 5)
  const [randomSeed, setRandomSeed] = useState(initialConfig.seed ?? 42)
  const [hasPreDefinedSplits, setHasPreDefinedSplits] = useState(false)
  const [predefinedSplitCounts, setPredefinedSplitCounts] = useState<{ train: number, val: number, test: number }>({ train: 0, val: 0, test: 0 })

  // Get the currently selected dataset summary (for file_count when WSI list not loaded)
  const selectedDataset = useMemo(() => {
    return availableDatasets.find(d => d.dataset_id === selectedDatasetId) || null
  }, [availableDatasets, selectedDatasetId])

  // Load available datasets on mount
  useEffect(() => {
    loadDatasets()
  }, [])

  // Pre-fetch WSI list in background when dataset is selected, to warm the cache before submit.
  // fetchWSIList has a client-side cache (wsiListCache), so when handleSubmit calls it,
  // it will hit the cache immediately instead of waiting for a large network request.
  useEffect(() => {
    if (selectedDatasetId) {
      fetchWSIList(selectedDatasetId).catch(() => { /* silently ignore - will retry on submit */ })
    }
  }, [selectedDatasetId])

  // Check if current split strategy is valid (for disabling submit button)
  // Simplified: only use file_count for rough validation since we submit by dataset_id
  const isSplitValid = useMemo(() => {
    if (splitStrategy === 'manual') {
      // For manual/custom splits, check if predefined splits exist
      return hasPreDefinedSplits
    }

    if (!selectedDataset) {
      return false
    }

    const fileCount = selectedDataset.file_count
    if (splitStrategy === 'random') {
      // Need at least 20 samples for 7:1:2 split (rough estimate)
      return fileCount >= 20
    }
    if (splitStrategy === 'k_fold') {
      // Need at least 2*k samples for k-fold (rough estimate)
      return fileCount >= kFoldSplits * 2
    }
    return true
  }, [splitStrategy, kFoldSplits, selectedDataset, hasPreDefinedSplits])

  // Track if we have a pending voice submit (waiting for data to load)
  const [pendingVoiceSubmit, setPendingVoiceSubmit] = useState(false)

  // Voice command submit trigger: when submitTrigger changes, mark pending submit
  useEffect(() => {
    // Only trigger if:
    // 1. submitTrigger is defined and changed
    // 2. Not already submitted or submitting
    if (
      submitTrigger !== undefined &&
      submitTrigger !== lastSubmitTrigger &&
      submitStatus === 'idle' &&
      !isSubmitting
    ) {
      setLastSubmitTrigger(submitTrigger)
      // Mark as pending - will submit when data is ready
      setPendingVoiceSubmit(true)
    }
  }, [submitTrigger, lastSubmitTrigger, submitStatus, isSubmitting])

  // Execute pending voice submit when data is ready
  // Only need dataset selected - handleSubmit will load WSIs on-demand if needed
  useEffect(() => {
    if (
      pendingVoiceSubmit &&
      !isLoadingDatasets &&
      selectedDatasetId &&
      submitStatus === 'idle' &&
      !isSubmitting
    ) {
      setPendingVoiceSubmit(false)
      handleSubmit()
    }
  }, [pendingVoiceSubmit, isLoadingDatasets, selectedDatasetId, submitStatus, isSubmitting])

  const loadDatasets = async () => {
    setIsLoadingDatasets(true)
    try {
      const result = await fetchDatasets()
      setAvailableDatasets(result.items)
      // If agent provided a dataset_id, verify it exists and set split info
      if (initialConfig.dataset_id) {
        const found = result.items.find(d => d.dataset_id === initialConfig.dataset_id)
        if (found) {
          setSelectedDatasetId(initialConfig.dataset_id)
          // Set split info immediately from dataset summary
          const hasSplits = found.has_predefined_splits ?? false
          const counts = found.predefined_split_counts ?? { train: 0, val: 0, test: 0 }
          setHasPreDefinedSplits(hasSplits)
          setPredefinedSplitCounts(counts)
          if (hasSplits && !initialConfig.split_strategy) {
            setSplitStrategy('manual')
          }
        }
      }
    } catch (error) {
      console.error('Failed to load datasets:', error)
    } finally {
      setIsLoadingDatasets(false)
    }
  }

  const updateConfig = (field: keyof AgentTaskConfig, value: any) => {
    const newConfig = { ...config, [field]: value }
    setConfig(newConfig)
    onConfigChange?.(newConfig)
    // Clear validation error for this field
    setValidationErrors(prev => prev.filter(e => e.field !== field))
  }

  const validate = (): boolean => {
    const errors: ValidationError[] = []
    if (!config.task_name?.trim()) {
      errors.push({ field: 'task_name', message: t('chatComponents.taskConfig.validation.taskNameRequired') })
    }
    if (!selectedDatasetId) {
      errors.push({ field: 'dataset_id', message: t('chatComponents.taskConfig.validation.selectDataset') })
    }
    if (splitStrategy === 'manual' && !hasPreDefinedSplits) {
      errors.push({ field: 'split', message: t('chatComponents.taskConfig.validation.noPreDefinedSplits') })
    }
    if (config.learning_rate && (config.learning_rate <= 0 || config.learning_rate > 1)) {
      errors.push({ field: 'learning_rate', message: t('chatComponents.taskConfig.validation.learningRateRange') })
    }
    if (config.epochs && (config.epochs < 1 || config.epochs > 1000)) {
      errors.push({ field: 'epochs', message: t('chatComponents.taskConfig.validation.epochsRange') })
    }
    if (config.batch_size && (config.batch_size < 1 || config.batch_size > 512)) {
      errors.push({ field: 'batch_size', message: t('chatComponents.taskConfig.validation.batchSizeRange') })
    }
    setValidationErrors(errors)
    return errors.length === 0
  }

  const handleSubmit = async () => {
    if (!validate()) return
    if (!selectedDatasetId) return

    // Check if there are any uploading tasks (upload or batch_import)
    if (hasUploadingTasks()) {
      setSubmitStatus('error')
      setErrorMessage(t('chatComponents.taskConfig.errors.uploadInProgress'))
      return
    }

    // Optimistic update: immediately show positive "pending" state
    // This disables the form and gives user instant feedback instead of a scary spinner
    setIsSubmitting(true)
    setSubmitStatus('pending')
    setErrorMessage('')

    try {
      // Load WSI list from dataset for submit
      const wsiListResult = await fetchWSIList(selectedDatasetId)
      const wsiIdsToUse = wsiListResult.items.map(wsi => wsi.wsi_id)
      const wsiDataForManualSplit = wsiListResult.items

      // Validate single-class tasks after loading WSI data
      const errors: ValidationError[] = []

      if (config.task_type === 'classification') {
        // For classification: check if there are at least 2 different labels
        const labels = new Set<string>()
        wsiDataForManualSplit.forEach(wsi => {
          if (wsi.label && wsi.label.trim()) {
            labels.add(wsi.label.trim())
          }
        })

        if (labels.size < 2) {
          const labelList = Array.from(labels).join(', ')
          errors.push({
            field: 'dataset_id',
            message: t('chatComponents.taskConfig.validation.classificationMinClasses', { count: labels.size, labels: labelList || t('chatComponents.taskConfig.none') })
          })
        }
      } else if (config.task_type === 'survival') {
        // For survival prediction: check if there are both event and censored samples
        let eventCount = 0
        let censoredCount = 0

        wsiDataForManualSplit.forEach(wsi => {
          if (wsi.event_status !== null && wsi.event_status !== undefined && wsi.event_time !== null && wsi.event_time !== undefined) {
            if (wsi.event_status === 1) {
              eventCount++
            } else if (wsi.event_status === 0) {
              censoredCount++
            }
          }
        })

        if (eventCount === 0 || censoredCount === 0) {
          const missingType = eventCount === 0 ? t('chatComponents.taskConfig.eventStatus1') : t('chatComponents.taskConfig.censoredStatus0')
          errors.push({
            field: 'dataset_id',
            message: t('chatComponents.taskConfig.validation.survivalBothRequired', { missingType, eventCount, censoredCount })
          })
        }
      }

      if (errors.length > 0) {
        setValidationErrors(errors)
        setSubmitStatus('error')  // Revert from pending to error
        setErrorMessage(errors[0].message)
        setIsSubmitting(false)
        return
      }

      // Build split config based on strategy
      let splitConfig: SplitConfig
      if (splitStrategy === 'manual') {
        // Construct manual splits from WSI data
        const manualSplits: Record<string, string> = {}
        wsiDataForManualSplit
          .filter(wsi => wsi.split)
          .forEach(wsi => {
            let s = wsi.split!.toLowerCase()
            if (s === 'validation') s = 'val'
            manualSplits[wsi.wsi_id] = s
          })
        splitConfig = { strategy: 'manual', manual_splits: manualSplits, seed: randomSeed }
      } else if (splitStrategy === 'k_fold') {
        splitConfig = { strategy: 'k_fold', n_splits: kFoldSplits, seed: randomSeed }
      } else {
        splitConfig = { strategy: 'random', ratios: { train: 0.7, val: 0.1, test: 0.2 }, seed: randomSeed }
      }

      // Build full TrainingTaskConfig using constants for defaults
      const fullConfig: TrainingTaskConfig = {
        task_name: config.task_name,
        task_type: config.task_type as 'classification' | 'survival' | 'segmentation',
        data_type: config.data_type,
        task_description: config.task_description || `Created by PathLab Agent`,
        wsi_ids: wsiIdsToUse,
        preprocessing: {
          // Note: tile_size removed - auto-determined by PrePATH-style tiling
          level: config.pyramid_level ?? DEFAULT_PYRAMID_LEVEL,
          // Feature extraction
          feature_extractor: config.encoder ?? DEFAULT_EXTRACTOR,
          feature_batch_size: config.feature_batch_size ?? DEFAULT_FEATURE_BATCH_SIZE,
          use_gpu: true,
          // Tissue segmentation parameters (WSI only)
          sthresh: config.sthresh ?? SEGMENTATION_DEFAULTS.sthresh,
          mthresh: config.mthresh ?? SEGMENTATION_DEFAULTS.mthresh,
          close: config.close ?? SEGMENTATION_DEFAULTS.close,
          use_otsu: config.use_otsu ?? SEGMENTATION_DEFAULTS.useOtsu,
        },
        model: {
          aggregator: config.aggregator ?? DEFAULT_AGGREGATOR,
          learning_rate: config.learning_rate ?? TRAINING_DEFAULTS.learningRate,
          epochs: config.epochs ?? TRAINING_DEFAULTS.epochs,
          optimizer: config.optimizer ?? TRAINING_DEFAULTS.optimizer,
          batch_size: config.batch_size ?? (config.data_type === 'wsi' ? 1 : TRAINING_DEFAULTS.batchSize),
          auto_balance: config.auto_balance ?? TRAINING_DEFAULTS.autoBalance,
          early_stopping_patience: config.early_stopping_patience ?? TRAINING_DEFAULTS.earlyStoppingPatience,
        },
        split_config: splitConfig
      }
      const result = await createTrainingTask(fullConfig)
      setSubmitStatus('success')
      onSubmitSuccess?.(result.task_id)
    } catch (error) {
      const msg = error instanceof Error ? error.message : t('chatComponents.taskConfig.errors.failedToCreate')
      setSubmitStatus('error')  // Revert from pending to error
      setErrorMessage(msg)
      onSubmitError?.(msg)
    } finally {
      setIsSubmitting(false)
    }
  }

  const getFieldError = (field: string) => validationErrors.find(e => e.field === field)?.message

  // Form is disabled after successful submission or during pending optimistic update
  const isFormDisabled = submitStatus === 'success' || submitStatus === 'pending' || isSubmitting

  // Check if this is an AI-recommended config - core fields should be locked
  const isAgentConfig = isAgentRecommendedConfig(initialConfig)

  // Core fields (task_type, data_type, dataset) are locked when AI recommends them
  const isCoreFieldLocked = isAgentConfig || isFormDisabled

  // Common disabled styles
  const disabledInputClass = isFormDisabled ? 'bg-gray-100 text-gray-500 cursor-not-allowed' : ''
  const disabledSelectClass = isFormDisabled ? 'bg-gray-100 text-gray-500 cursor-not-allowed' : ''
  const lockedSelectClass = isCoreFieldLocked ? 'bg-gray-100 text-gray-600 cursor-not-allowed' : ''

  return (
    <div className="mt-4 bg-white border border-gray-200 rounded-2xl shadow-sm overflow-hidden">
      {/* Header */}
      <div className="px-5 py-4 bg-gradient-to-r from-primary-50 to-blue-50 border-b border-gray-100">
        <h3 className="font-semibold text-gray-900 flex items-center gap-2">
          <Play className="w-4 h-4 text-primary-600" />
          {t('chatComponents.taskConfig.title')}
        </h3>
        <p className="text-sm text-gray-500 mt-1">
          {submitStatus === 'success'
            ? t('chatComponents.taskConfig.subtitleSuccess')
            : submitStatus === 'pending'
              ? t('chatComponents.taskConfig.subtitlePending')
              : t('chatComponents.taskConfig.subtitleDefault')}
        </p>
      </div>

      {/* Form Fields */}
      <div className="p-5 space-y-4">
        {/* Task Name */}
        <div>
          <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.taskName')}</label>
          <input
            type="text"
            value={config.task_name || ''}
            onChange={(e) => updateConfig('task_name', e.target.value)}
            disabled={isFormDisabled}
            className={`w-full px-3 py-2 border rounded-lg text-sm focus:ring-2 focus:ring-primary-100 focus:border-primary-400 ${getFieldError('task_name') ? 'border-red-300 bg-red-50' : 'border-gray-200'
              } ${disabledInputClass}`}
            placeholder={t('chatComponents.taskConfig.taskNamePlaceholder')}
          />
          {getFieldError('task_name') && (
            <p className="text-xs text-red-500 mt-1">{getFieldError('task_name')}</p>
          )}
        </div>

        {/* Task Type & Data Level - Locked when AI recommends */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.taskType')}</label>
            <select
              value={config.task_type}
              onChange={(e) => updateConfig('task_type', e.target.value)}
              disabled={isCoreFieldLocked}
              className={`w-full px-3 py-2 border border-gray-200 rounded-lg text-sm focus:ring-2 focus:ring-primary-100 ${lockedSelectClass}`}
            >
              {FIELD_OPTIONS.task_type.map(opt => (
                <option key={opt.value} value={opt.value}>{opt.label}</option>
              ))}
            </select>
          </div>
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.dataLevel')}</label>
            <select
              value={config.data_type}
              onChange={(e) => updateConfig('data_type', e.target.value)}
              disabled={isCoreFieldLocked}
              className={`w-full px-3 py-2 border border-gray-200 rounded-lg text-sm focus:ring-2 focus:ring-primary-100 ${lockedSelectClass}`}
            >
              {FIELD_OPTIONS.data_type.map(opt => (
                <option key={opt.value} value={opt.value}>{opt.label}</option>
              ))}
            </select>
          </div>
        </div>

        {/* Dataset Selection - Locked when AI recommends */}
        <div>
          <label className="block text-sm font-medium text-gray-700 mb-1">
            {t('chatComponents.taskConfig.selectDataset')} {selectedDataset && (
              <span className="text-gray-500 font-normal">
                ({t('chatComponents.taskConfig.filesWillBeUsed', { count: selectedDataset.file_count })})
              </span>
            )}
          </label>
          {isLoadingDatasets ? (
            <div className="flex items-center gap-2 text-sm text-gray-500 py-2">
              <Loader2 className="w-4 h-4 animate-spin" />
              {t('chatComponents.taskConfig.loadingDatasets')}
            </div>
          ) : availableDatasets.length === 0 ? (
            <p className="text-sm text-amber-600 py-2">{t('chatComponents.taskConfig.noDatasetsAvailable')}</p>
          ) : (
            <select
              value={selectedDatasetId || ''}
              onChange={(e) => {
                const newDatasetId = e.target.value || null
                setSelectedDatasetId(newDatasetId)
                setValidationErrors(prev => prev.filter(err => err.field !== 'dataset_id'))

                // Immediately update split info from dataset summary
                if (newDatasetId) {
                  const selectedDataset = availableDatasets.find(d => d.dataset_id === newDatasetId)
                  if (selectedDataset) {
                    const hasSplits = selectedDataset.has_predefined_splits ?? false
                    const counts = selectedDataset.predefined_split_counts ?? { train: 0, val: 0, test: 0 }
                    setHasPreDefinedSplits(hasSplits)
                    setPredefinedSplitCounts(counts)
                    // Auto-select manual split if CSV splits are available
                    if (hasSplits) {
                      setSplitStrategy('manual')
                    }
                  }
                } else {
                  setHasPreDefinedSplits(false)
                  setPredefinedSplitCounts({ train: 0, val: 0, test: 0 })
                }
              }}
              disabled={isCoreFieldLocked}
              className={`w-full px-3 py-2 border rounded-lg text-sm focus:ring-2 focus:ring-primary-100 ${getFieldError('dataset_id') ? 'border-red-300 bg-red-50' : 'border-gray-200'
                } ${lockedSelectClass}`}
            >
              <option value="">{t('chatComponents.taskConfig.selectDatasetPlaceholder')}</option>
              {availableDatasets.map(dataset => (
                <option key={dataset.dataset_id || 'uncategorized'} value={dataset.dataset_id || ''}>
                  {dataset.dataset_name} ({t('chatComponents.taskConfig.filesCount', { count: dataset.file_count })})
                </option>
              ))}
            </select>
          )}
          {getFieldError('dataset_id') && (
            <p className="text-xs text-red-500 mt-1">{getFieldError('dataset_id')}</p>
          )}
        </div>

        {/* Split Strategy Configuration */}
        {selectedDatasetId && (
          <div className={`border border-gray-100 rounded-lg p-4 bg-gray-50 ${isFormDisabled ? 'opacity-70' : ''}`}>
            <div className="flex items-center gap-2 mb-3">
              <Layers className="w-4 h-4 text-gray-500" />
              <span className="text-sm font-medium text-gray-700">{t('chatComponents.taskConfig.splitStrategy')}</span>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-2">
              {/* Random Split */}
              <button
                type="button"
                onClick={() => !isFormDisabled && setSplitStrategy('random')}
                disabled={isFormDisabled}
                className={`p-3 rounded-lg border text-left transition-all ${splitStrategy === 'random'
                  ? 'bg-primary-50 border-primary-500 ring-1 ring-primary-500'
                  : 'bg-white border-gray-200 hover:border-primary-300'
                  } ${isFormDisabled ? 'cursor-not-allowed' : ''}`}
              >
                <div className="flex items-center gap-1.5 mb-1">
                  <div className={`w-3 h-3 rounded-full border flex items-center justify-center ${splitStrategy === 'random' ? 'border-primary-600' : 'border-gray-400'
                    }`}>
                    {splitStrategy === 'random' && <div className="w-1.5 h-1.5 rounded-full bg-primary-600" />}
                  </div>
                  <span className={`font-medium text-xs ${isFormDisabled ? 'text-gray-500' : 'text-gray-900'}`}>{t('chatComponents.taskConfig.splitRandom')}</span>
                </div>
                <p className="text-[10px] text-gray-500 ml-4.5">{t('chatComponents.taskConfig.splitRandomDesc')}</p>
              </button>

              {/* K-Fold */}
              <button
                type="button"
                onClick={() => !isFormDisabled && setSplitStrategy('k_fold')}
                disabled={isFormDisabled}
                className={`p-3 rounded-lg border text-left transition-all ${splitStrategy === 'k_fold'
                  ? 'bg-primary-50 border-primary-500 ring-1 ring-primary-500'
                  : 'bg-white border-gray-200 hover:border-primary-300'
                  } ${isFormDisabled ? 'cursor-not-allowed' : ''}`}
              >
                <div className="flex items-center gap-1.5 mb-1">
                  <div className={`w-3 h-3 rounded-full border flex items-center justify-center ${splitStrategy === 'k_fold' ? 'border-primary-600' : 'border-gray-400'
                    }`}>
                    {splitStrategy === 'k_fold' && <div className="w-1.5 h-1.5 rounded-full bg-primary-600" />}
                  </div>
                  <span className={`font-medium text-xs ${isFormDisabled ? 'text-gray-500' : 'text-gray-900'}`}>{t('chatComponents.taskConfig.splitKFold')}</span>
                </div>
                <p className="text-[10px] text-gray-500 ml-4.5">{t('chatComponents.taskConfig.splitKFoldDesc')}</p>
              </button>

              {/* Manual Split (CSV) */}
              <button
                type="button"
                onClick={() => !isFormDisabled && hasPreDefinedSplits && setSplitStrategy('manual')}
                disabled={isFormDisabled || !hasPreDefinedSplits}
                className={`p-3 rounded-lg border text-left transition-all ${splitStrategy === 'manual'
                  ? 'bg-primary-50 border-primary-500 ring-1 ring-primary-500'
                  : hasPreDefinedSplits && !isFormDisabled
                    ? 'bg-white border-gray-200 hover:border-primary-300'
                    : 'bg-gray-100 border-gray-200 cursor-not-allowed opacity-60'
                  }`}
              >
                <div className="flex items-center gap-1.5 mb-1">
                  <div className={`w-3 h-3 rounded-full border flex items-center justify-center ${splitStrategy === 'manual' ? 'border-primary-600' : 'border-gray-400'
                    }`}>
                    {splitStrategy === 'manual' && <div className="w-1.5 h-1.5 rounded-full bg-primary-600" />}
                  </div>
                  <span className={`font-medium text-xs ${isFormDisabled ? 'text-gray-500' : 'text-gray-900'}`}>{t('chatComponents.taskConfig.splitCustom')}</span>
                </div>
                <p className="text-[10px] text-gray-500 ml-4.5">
                  {hasPreDefinedSplits ? t('chatComponents.taskConfig.splitFromCSV') : t('chatComponents.taskConfig.splitNoSplitsFound')}
                </p>
              </button>
            </div>

            {/* Split Strategy Details */}
            <div className="mt-3">
              {splitStrategy === 'random' && (
                <div className="space-y-2">
                  <div className="flex items-center gap-3 text-xs p-2 rounded border bg-white border-gray-100 text-gray-600">
                    <span className="flex items-center gap-1"><span className="w-2 h-2 rounded-full bg-green-500"></span>{t('chatComponents.taskConfig.trainPercent')}</span>
                    <span className="flex items-center gap-1"><span className="w-2 h-2 rounded-full bg-blue-500"></span>{t('chatComponents.taskConfig.valPercent')}</span>
                    <span className="flex items-center gap-1"><span className="w-2 h-2 rounded-full bg-orange-500"></span>{t('chatComponents.taskConfig.testPercent')}</span>
                  </div>
                  {selectedDataset && (
                    <div className="text-[10px] text-gray-500">
                      {t('chatComponents.taskConfig.sampleCount', { count: selectedDataset.file_count })}
                    </div>
                  )}
                </div>
              )}
              {splitStrategy === 'k_fold' && (
                <div className="space-y-2">
                  <div className="flex items-center gap-2 bg-white p-2 rounded border border-gray-100">
                    <label className="text-xs text-gray-600">{t('chatComponents.taskConfig.foldsK')}:</label>
                    <input
                      type="number"
                      min={2}
                      max={10}
                      value={kFoldSplits}
                      onChange={(e) => {
                        setKFoldSplits(Math.max(2, Math.min(10, parseInt(e.target.value) || 5)))
                      }}
                      disabled={isFormDisabled}
                      className={`w-14 px-2 py-1 text-xs border border-gray-200 rounded focus:ring-1 focus:ring-primary-500 ${disabledInputClass}`}
                    />
                  </div>
                  {selectedDataset && (
                    <div className="text-[10px] text-blue-600">
                      {t('chatComponents.taskConfig.kFoldInfo', { k: kFoldSplits, count: selectedDataset.file_count })}
                    </div>
                  )}
                </div>
              )}
              {splitStrategy === 'manual' && hasPreDefinedSplits && (
                <div className="space-y-2">
                  <div className="flex items-center gap-2 text-xs text-green-700 bg-green-50 p-2 rounded border border-green-100">
                    <CheckCircle className="w-3.5 h-3.5 text-green-600 shrink-0" />
                    <span className="font-medium">{t('chatComponents.taskConfig.readyToUseSplits')}</span>
                  </div>
                  <div className="flex items-center gap-3 text-xs text-gray-600 bg-white p-2 rounded border border-gray-100">
                    <span>{t('chatComponents.taskConfig.trainLabel')}: {predefinedSplitCounts.train}</span>
                    <span>{t('chatComponents.taskConfig.valLabel')}: {predefinedSplitCounts.val}</span>
                    <span>{t('chatComponents.taskConfig.testLabel')}: {predefinedSplitCounts.test}</span>
                  </div>
                </div>
              )}
            </div>
          </div>
        )}

        {/* Encoder & Model (Aggregator for WSI, Linear Probe for Patch) */}
        <div className="grid grid-cols-2 gap-4">
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">
              {config.data_type === 'patch' ? t('chatComponents.taskConfig.featureExtractor') : t('chatComponents.taskConfig.encoder')}
            </label>
            <select
              value={config.encoder || 'resnet50'}
              onChange={(e) => updateConfig('encoder', e.target.value)}
              disabled={isFormDisabled}
              className={`w-full px-3 py-2 border border-gray-200 rounded-lg text-sm focus:ring-2 focus:ring-primary-100 ${disabledSelectClass}`}
            >
              {FIELD_OPTIONS.encoder.map(opt => (
                <option key={opt.value} value={opt.value}>{opt.label}</option>
              ))}
            </select>
          </div>
          {config.data_type === 'wsi' ? (
            <div>
              <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.aggregator')}</label>
              <select
                value={config.aggregator || 'abmil'}
                onChange={(e) => updateConfig('aggregator', e.target.value)}
                disabled={isFormDisabled}
                className={`w-full px-3 py-2 border border-gray-200 rounded-lg text-sm focus:ring-2 focus:ring-primary-100 ${disabledSelectClass}`}
              >
                {FIELD_OPTIONS.aggregator.map(opt => (
                  <option key={opt.value} value={opt.value}>{opt.label}</option>
                ))}
              </select>
            </div>
          ) : (
            <div>
              <label className="block text-sm font-medium text-gray-700 mb-1">{t('chatComponents.taskConfig.model')}</label>
              <div className="w-full px-3 py-2 border border-gray-200 rounded-lg text-sm bg-gray-100 text-gray-500">
                {t('chatComponents.taskConfig.linearProbe')}
              </div>
              <p className="text-[10px] text-gray-400 mt-1">{t('chatComponents.taskConfig.linearProbeDesc')}</p>
            </div>
          )}
        </div>

        {/* Advanced Settings Toggle */}
        <button
          type="button"
          onClick={() => setShowAdvanced(!showAdvanced)}
          className={`flex items-center gap-1 text-sm ${isFormDisabled ? 'text-gray-400' : 'text-gray-500 hover:text-gray-700'}`}
        >
          {showAdvanced ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
          {t('chatComponents.taskConfig.advancedSettings')}
        </button>

        {/* Advanced Settings */}
        {showAdvanced && (
          <div className="grid grid-cols-2 gap-4 pt-2 border-t border-gray-100">
            <div>
              <label className="block text-xs font-medium text-gray-600 mb-1">{t('chatComponents.taskConfig.learningRate')}</label>
              <input
                type="text"
                inputMode="decimal"
                value={learningRateInput}
                onChange={(e) => {
                  const val = e.target.value
                  // Allow any valid decimal input pattern (including intermediate states like "0." or ".")
                  if (val === '' || /^[0-9]*\.?[0-9]*$/.test(val)) {
                    setLearningRateInput(val)
                    // Only update config when we have a valid number
                    const num = parseFloat(val)
                    if (!isNaN(num) && num > 0) {
                      updateConfig('learning_rate', num)
                    }
                  }
                }}
                onBlur={() => {
                  // On blur, ensure a valid value (default to 0.0001 if empty/invalid)
                  const num = parseFloat(learningRateInput)
                  if (isNaN(num) || num <= 0) {
                    setLearningRateInput('0.0001')
                    updateConfig('learning_rate', 0.0001)
                  } else {
                    // Normalize the display (remove trailing dots, etc.)
                    setLearningRateInput(num.toString())
                  }
                }}
                disabled={isFormDisabled}
                className={`w-full px-2 py-1.5 border rounded text-sm ${getFieldError('learning_rate') ? 'border-red-300' : 'border-gray-200'
                  } ${disabledInputClass}`}
              />
            </div>
            <div>
              <label className="block text-xs font-medium text-gray-600 mb-1">{t('chatComponents.taskConfig.epochs')}</label>
              <input
                type="number"
                value={config.epochs || 50}
                onChange={(e) => updateConfig('epochs', parseInt(e.target.value))}
                disabled={isFormDisabled}
                className={`w-full px-2 py-1.5 border rounded text-sm ${getFieldError('epochs') ? 'border-red-300' : 'border-gray-200'
                  } ${disabledInputClass}`}
              />
            </div>
            <div>
              <label className="block text-xs font-medium text-gray-600 mb-1">{t('chatComponents.taskConfig.batchSize')}</label>
              <input
                type="number"
                value={config.batch_size ?? (config.data_type === 'wsi' ? 1 : TRAINING_DEFAULTS.batchSize)}
                onChange={(e) => updateConfig('batch_size', parseInt(e.target.value))}
                disabled={isFormDisabled}
                className={`w-full px-2 py-1.5 border rounded text-sm ${getFieldError('batch_size') ? 'border-red-300' : 'border-gray-200'
                  } ${disabledInputClass}`}
              />
            </div>
            <div>
              <label className="block text-xs font-medium text-gray-600 mb-1">{t('chatComponents.taskConfig.randomSeed')}</label>
              <input
                type="number"
                value={randomSeed}
                onChange={(e) => setRandomSeed(parseInt(e.target.value) || 42)}
                disabled={isFormDisabled}
                className={`w-full px-2 py-1.5 border border-gray-200 rounded text-sm ${disabledInputClass}`}
              />
            </div>
          </div>
        )}
      </div>

      {/* Error Message */}
      {submitStatus === 'error' && errorMessage && (
        <div className="mx-5 mb-4 p-3 bg-red-50 border border-red-200 rounded-lg flex items-start gap-2">
          <AlertCircle className="w-4 h-4 text-red-500 mt-0.5 flex-shrink-0" />
          <div>
            <p className="text-sm font-medium text-red-700">{t('chatComponents.taskConfig.errors.failedToCreateTitle')}</p>
            <p className="text-xs text-red-600 mt-0.5">{errorMessage}</p>
            {(() => {
              const lower = errorMessage.toLowerCase()
              if (lower.includes('external storage not responding') ||
                  (lower.includes('storage') && lower.includes('timed out')) ||
                  (lower.includes('not accessible') && lower.includes('file'))) {
                return (
                  <p className="text-xs text-red-500 mt-1.5 flex items-start gap-1">
                    <span>{t('chatComponents.taskConfig.errors.storageUnreachable')}</span>
                  </p>
                )
              }
              return null
            })()}
          </div>
        </div>
      )}

      {/* Success Message */}
      {submitStatus === 'success' && (
        <div className="mx-5 mb-4 p-3 bg-green-50 border border-green-200 rounded-lg flex items-center gap-2">
          <CheckCircle className="w-4 h-4 text-green-500" />
          <p className="text-sm font-medium text-green-700">{t('chatComponents.taskConfig.taskCreatedSuccess')}</p>
        </div>
      )}

      {/* Helpfulness Feedback */}
      {submitStatus === 'success' && !helpfulnessFeedback && (
        <div className="mx-5 mb-4 p-4 bg-blue-50 border border-blue-200 rounded-lg">
          <p className="text-sm font-medium text-blue-800 mb-3">{t('chatComponents.taskConfig.helpfulnessQuestion')}</p>
          <div className="flex gap-2">
            <button
              onClick={() => {
                setHelpfulnessFeedback('helpful')
                const taskId = config.submitted_task_id || ''
                if (messageId && onHelpfulnessFeedback) {
                  onHelpfulnessFeedback(messageId, 'helpful', taskId, 'training', config.task_name || undefined)
                }
              }}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-white border border-blue-200 hover:bg-green-50 hover:border-green-300 hover:text-green-700 text-blue-700 rounded-md text-sm font-medium transition-all shadow-sm"
            >
              <ThumbsUp className="w-3.5 h-3.5" />
              {t('chatComponents.taskConfig.yes')}
            </button>
            <button
              onClick={() => {
                setHelpfulnessFeedback('not_helpful')
                const taskId = config.submitted_task_id || ''
                if (messageId && onHelpfulnessFeedback) {
                  onHelpfulnessFeedback(messageId, 'not_helpful', taskId, 'training', config.task_name || undefined)
                }
              }}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-white border border-blue-200 hover:bg-red-50 hover:border-red-300 hover:text-red-700 text-blue-700 rounded-md text-sm font-medium transition-all shadow-sm"
            >
              <ThumbsDown className="w-3.5 h-3.5" />
              {t('chatComponents.taskConfig.no')}
            </button>
          </div>
        </div>
      )}

      {/* Helpfulness Feedback Submitted */}
      {submitStatus === 'success' && helpfulnessFeedback && (
        <div className="mx-5 mb-4 p-3 bg-gray-50 border border-gray-200 rounded-lg flex items-center gap-2">
          {helpfulnessFeedback === 'helpful' ? (
            <ThumbsUp className="w-4 h-4 text-green-500" />
          ) : (
            <ThumbsDown className="w-4 h-4 text-red-500" />
          )}
          <p className="text-sm text-gray-600">
            {t('chatComponents.taskConfig.feedbackThanks')}
          </p>
        </div>
      )}

      {/* Submit Button */}
      <div className="px-5 py-4 bg-gray-50 border-t border-gray-100">
        <button
          onClick={handleSubmit}
          disabled={isSubmitting || submitStatus === 'success' || submitStatus === 'pending' || !isSplitValid}
          className={`w-full py-2.5 rounded-lg font-medium text-sm
                     flex items-center justify-center gap-2 transition-colors
                     ${submitStatus === 'pending'
                       ? 'bg-green-500 text-white cursor-not-allowed'
                       : submitStatus === 'success'
                         ? 'bg-green-500 text-white cursor-not-allowed'
                         : 'bg-primary-600 text-white hover:bg-primary-700 active:bg-primary-800 disabled:bg-gray-300 disabled:cursor-not-allowed'
                     }`}
        >
          {submitStatus === 'pending' ? (
            <>
              <CheckCircle className="w-4 h-4" />
              {t('chatComponents.taskConfig.creatingTask')}
            </>
          ) : submitStatus === 'success' ? (
            <>
              <CheckCircle className="w-4 h-4" />
              {t('chatComponents.taskConfig.taskCreated')}
            </>
          ) : (
            <>
              <Play className="w-4 h-4" />
              {t('chatComponents.taskConfig.startTraining')}
            </>
          )}
        </button>
      </div>
    </div>
  )
}
