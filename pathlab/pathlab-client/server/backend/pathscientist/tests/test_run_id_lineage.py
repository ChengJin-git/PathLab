"""Tests for run_id guarantees across the lineage.

Covers Task 3 of the Session Integrity Hardening plan: IterationState must
always produce a non-empty run_id, and that run_id must flow end-to-end into
MetricsTracker.history and IterationState.finalized_run_ids so IntegrityGuard
can cross-reference them.

Motivating defect: session_142a4acaed08 had ``tracker_state.history[*].run_id``
blank for all 6 entries because the agent committed without ever calling
``run_experiment`` (the component that populates ``last_run_id``).
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent.parent))
os.environ["OPENHANDS_SUPPRESS_BANNER"] = "1"

import pytest

from pathscientist.runtime.iteration_state import IterationState
from pathscientist.runtime.session_registry import (
    SessionDeps,
    register_session,
    remove_session,
)
from pathscientist.tools.metrics import MetricsTracker
from pathscientist.tools.ratchet import _finalize_iteration


# ---------- ensure_run_id helper ----------


def test_ensure_run_id_generates_when_blank():
    """ensure_run_id() returns a fresh uuid hex when last_run_id is empty."""
    state = IterationState(max_iterations=5)
    assert state.last_run_id == ""
    generated = state.ensure_run_id()
    assert generated
    assert generated == state.last_run_id
    assert len(generated) == 8  # uuid4().hex[:8]


def test_ensure_run_id_is_idempotent_when_set():
    """ensure_run_id() returns the existing run_id without changing it."""
    state = IterationState(max_iterations=5)
    state.last_run_id = "preset01"
    assert state.ensure_run_id() == "preset01"
    assert state.last_run_id == "preset01"


# ---------- _finalize_iteration run_id propagation ----------


def _make_session(session_id: str) -> SessionDeps:
    """Build a minimal SessionDeps for the registry."""
    tracker = MetricsTracker(primary_metric="auc")
    iteration_state = IterationState(max_iterations=5)
    deps = SessionDeps(
        workspace=None,
        tracker=tracker,
        config=None,
        iteration_state=iteration_state,
        conversation=None,
        last_experiment=None,
    )
    register_session(session_id, deps)
    return deps


def test_run_id_propagates_from_run_experiment_to_tracker():
    """When run_experiment set last_run_id, tracker.history carries it forward."""
    session_id = "test_run_id_propagates_session"
    deps = _make_session(session_id)
    try:
        # Simulate run_experiment having populated last_run_id.
        deps.iteration_state.last_run_id = "abc12345"

        _finalize_iteration(session_id, metrics={"auc": 0.8}, committed=True)

        assert len(deps.tracker.history) == 1
        assert deps.tracker.history[-1]["run_id"] == "abc12345"
        assert deps.iteration_state.finalized_run_ids[-1] == "abc12345"
    finally:
        remove_session(session_id)


def test_run_id_autogenerated_when_missing():
    """Without run_experiment, _finalize_iteration still produces a traceable run_id."""
    session_id = "test_run_id_autogenerated_session"
    deps = _make_session(session_id)
    try:
        # last_run_id intentionally NOT set — agent committed without run_experiment.
        assert deps.iteration_state.last_run_id == ""

        _finalize_iteration(session_id, metrics={"auc": 0.6}, committed=True)

        assert len(deps.tracker.history) == 1
        recorded_run_id = deps.tracker.history[-1]["run_id"]
        assert recorded_run_id != ""
        assert deps.iteration_state.finalized_run_ids, (
            "finalized_run_ids must be populated even when last_run_id was blank"
        )
        assert deps.iteration_state.finalized_run_ids[-1] == recorded_run_id
    finally:
        remove_session(session_id)


def test_consecutive_finalizations_use_distinct_run_ids():
    """Back-to-back _finalize_iteration calls must mint distinct run_ids.

    Motivating defect: session_b14b074d2268 (2026-04-20) had
    ``finalized_run_ids == ['2c696802'] * 17`` because ``last_run_id`` was
    never cleared between iterations and ``ensure_run_id()`` is idempotent
    when ``last_run_id`` is already set. Every subsequent call reused the
    first generated id, collapsing 17 distinct iterations into one.

    Contract: after each finalization, ``last_run_id`` must be reset so the
    next iteration's ``ensure_run_id()`` mints a fresh uuid. This test does
    NOT touch ``deps.iteration_state.last_run_id`` between calls — that is
    precisely the path the agent takes when it bypasses ``RunExperimentTool``.
    """
    session_id = "test_consecutive_finalizations_distinct_run_ids_session"
    deps = _make_session(session_id)
    try:
        # Agent reaches finalization without run_experiment having populated
        # last_run_id. First call auto-generates a uuid.
        assert deps.iteration_state.last_run_id == ""
        _finalize_iteration(session_id, metrics={"auc": 0.8}, committed=True)

        # Second call WITHOUT resetting last_run_id — simulates the terminal
        # + python train.py + ratchet_commit bypass path that caused the bug.
        _finalize_iteration(session_id, metrics={"auc": 0.9}, committed=True)

        finalized = deps.iteration_state.finalized_run_ids
        assert len(finalized) == 2
        assert finalized[0] != finalized[1], (
            f"Expected distinct run_ids across iterations, got {finalized} — "
            "last_run_id is sticky across _finalize_iteration calls."
        )
        assert len(set(finalized)) == 2

        # Tracker history must agree element-wise.
        assert len(deps.tracker.history) == 2
        assert deps.tracker.history[0]["run_id"] == finalized[0]
        assert deps.tracker.history[1]["run_id"] == finalized[1]
    finally:
        remove_session(session_id)


def test_finalized_run_ids_matches_tracker_history_length():
    """After N finalizations, finalized_run_ids and tracker.history stay aligned."""
    session_id = "test_finalized_run_ids_length_session"
    deps = _make_session(session_id)
    try:
        # Mix of preset and blank run_ids across iterations.
        scenarios = [
            ("preset01", True),  # run_experiment populated last_run_id, commit
            ("", True),           # blank → autogenerated, commit
            ("preset03", False),  # run_experiment populated last_run_id, revert
            ("", False),           # blank → autogenerated, revert
        ]

        for preset_id, committed in scenarios:
            deps.iteration_state.last_run_id = preset_id
            _finalize_iteration(session_id, metrics={"auc": 0.5}, committed=committed)

        assert len(deps.tracker.history) == len(scenarios)
        assert len(deps.iteration_state.finalized_run_ids) == len(scenarios)

        # And run_ids must correspond element-wise.
        for tracker_entry, committed_run_id in zip(
            deps.tracker.history,
            deps.iteration_state.finalized_run_ids,
            strict=True,
        ):
            assert tracker_entry["run_id"] == committed_run_id
            assert tracker_entry["run_id"] != ""
    finally:
        remove_session(session_id)


